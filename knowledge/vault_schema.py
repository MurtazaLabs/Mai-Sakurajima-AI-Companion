"""Canonical vault schema — single source of truth for folder/owner/write-mode.

This module encodes the invariants from docs/cognitive-architecture-state-first.md:

1. One canonical folder name per category (never both `conversation/` and
   `conversations/`, nor `relationship/` and `relationships/`).
2. Only the VaultCompiler writes to the vault. Every other subsystem updates
   runtime state and requests a compile.

`VAULT_FOLDERS` is the authoritative list of canonical vault folders. Any folder
not in this set that is found at boot is treated as a legacy/orphan folder and
flagged by the boot invariant check.
"""

from enum import Enum
from pathlib import Path

from config.paths import OBSIDIAN_VAULT


class WriteMode(str, Enum):
    APPEND = "append"          # conversation logs only (immutable turns)
    REWRITE = "rewrite"        # regenerated fully from MemoryState by compiler
    GRAPH = "graph"            # generated by the knowledge-graph exporter


# Folder -> (owner subsystem, write mode)
# Owner is the ONLY subsystem permitted to write that folder. In Phase 1 every
# owner is "VaultCompiler" except `conversation` (append-only by Conversation
# Engine) and `Entities` (knowledge-graph sync). Phase 2/3 will fully enforce.
VAULT_SCHEMA: dict[str, dict[str, str]] = {
    "conversation":  {"owner": "ConversationEngine", "mode": WriteMode.APPEND.value},
    "identity":      {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "preferences":   {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "relationship":  {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "reflections":   {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "knowledge":     {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "people":        {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "places":        {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "projects":      {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "statistics":    {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "dreams":        {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
    "archive":       {"owner": "VaultCompiler",      "mode": WriteMode.APPEND.value},
    "important":     {"owner": "VaultCompiler",      "mode": WriteMode.APPEND.value},
    # Phase 3/4: entities are exported to `graph/` (canonical). `Entities/` is
    # retired in favor of `graph/` (see docs/cognitive-architecture-state-first.md).
    "graph":         {"owner": "GraphExporter",      "mode": WriteMode.GRAPH.value},
    # Phase 3 proposed layout additions.
    "maintenance":   {"owner": "VaultCompiler",      "mode": WriteMode.REWRITE.value},
}

# Canonical top-level markdown files generated by the VaultCompiler.
# name -> owner subsystem
VAULT_FILES: dict[str, str] = {
    "index.md": "VaultCompiler",
    "schema.md": "VaultCompiler",
    "log.md": "VaultCompiler",
}

# Canonical set of permitted top-level vault folders.
VAULT_FOLDERS: set[str] = set(VAULT_SCHEMA.keys())

# Known legacy folder names that must NOT exist (Phase 1 migration residual).
LEGACY_VAULT_FOLDERS: set[str] = {
    "conversations",   # singular `conversation` is canonical
    "relationships",   # singular `relationship` is canonical
}

# Folders owned exclusively by the VaultCompiler in the current phase.
COMPILER_OWNED_FOLDERS: set[str] = {
    name for name, meta in VAULT_SCHEMA.items()
    if meta["owner"] == "VaultCompiler"
}


def folder_owner(folder: str) -> str:
    return VAULT_SCHEMA.get(folder, {}).get("owner", "UNKNOWN")


def folder_write_mode(folder: str) -> str:
    return VAULT_SCHEMA.get(folder, {}).get("mode", WriteMode.APPEND.value)


def assert_no_legacy_folders(vault_root: Path = OBSIDIAN_VAULT) -> None:
    """Boot invariant: no legacy/duplicate vault folders may exist.

    Raises FileExistsError if any legacy folder is present (it should have been
    removed by knowledge/vault_migrator.py during build). This enforces the
    single-canonical-folder-name invariant from the architecture doc.
    """
    vault_root = Path(vault_root)
    if not vault_root.exists():
        return
    found = [f.name for f in vault_root.iterdir()
             if f.is_dir() and f.name in LEGACY_VAULT_FOLDERS]
    if found:
        raise FileExistsError(
            f"[VaultSchema] Legacy vault folders present and must be migrated: "
            f"{found}. Run knowledge.vault_migrator.migrate_vault()."
        )


def scan_unknown_folders(vault_root: Path = OBSIDIAN_VAULT) -> list:
    """Return non-canonical top-level folders (excluding dot-folders / files)."""
    vault_root = Path(vault_root)
    if not vault_root.exists():
        return []
    return [
        f.name for f in vault_root.iterdir()
        if f.is_dir() and not f.name.startswith(".")
        and f.name not in VAULT_FOLDERS
    ]

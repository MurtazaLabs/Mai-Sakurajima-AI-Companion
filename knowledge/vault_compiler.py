"""VaultCompiler — the single canonical writer to the Obsidian vault.

Phase 1 of docs/cognitive-architecture-state-first.md. This is a thin facade over
the existing ObsidianWriter that establishes ONE entry point for generating vault
markdown from runtime state. No behavior changes yet: every existing call path
(ObsidianWriter.dump / sync / write_memory) is preserved underneath.

Long-term goal (Phase 2/3): every subsystem updates MemoryState / the knowledge
graph and asks the VaultCompiler to compile. Direct ObsidianWriter.* calls from
outside this module will be deprecated.
"""

import logging

from knowledge.vault_logger import VaultLogger
from knowledge.vault_schema import (
    COMPILER_OWNED_FOLDERS,
    VAULT_FILES,
    VAULT_FOLDERS,
    VAULT_SCHEMA,
)

logger = logging.getLogger(__name__)


class VaultCompiler:
    """Centralized vault-writing facade.

    Wraps an ObsidianWriter and exposes intent-named compile methods so callers
    express WHAT they want written (the state) rather than HOW (raw markdown IO).
    """

    def __init__(self, writer):
        self._writer = writer
        self.vault_root = getattr(writer, "vault_root", None)
        self.logger = VaultLogger(self.vault_root)

    # ── Delegated low-level writers (kept for backward compatibility) ──

    def sync_graph(self, *args, **kwargs):
        """Sync the knowledge-graph entities (Entities/ folder)."""
        return self._writer.sync(*args, **kwargs)

    def write_memory(self, *args, **kwargs):
        """Legacy per-turn memory persistence (conversation/ folder, append)."""
        return self._writer.write_memory(*args, **kwargs)

    def write_important(self, *args, **kwargs):
        return self._writer.write_important(*args, **kwargs)

    def write_reflection(self, *args, **kwargs):
        return self._writer.write_reflection(*args, **kwargs)

    def archive(self, *args, **kwargs):
        return self._writer.archive(*args, **kwargs)

    def write_statistics(self, *args, **kwargs):
        return self._writer.write_statistics(*args, **kwargs)

    # ── Intent-named compile from runtime MemoryState ──

    def compile_state(self, state, date_str) -> None:
        """Regenerate all compiler-owned folders from a MemoryState snapshot.

        This is the canonical "state -> vault" operation. Folders written here
        are exactly COMPILER_OWNED_FOLDERS (see vault_schema.py).
        """
        if self._writer is None:
            return
        try:
            self._writer.dump(state, date_str)
            logger.info("[VaultCompiler] compiled MemoryState -> vault "
                        f"(date={date_str}, folders={sorted(COMPILER_OWNED_FOLDERS)})")
            self.logger.knowledge_merged(f"date={date_str}")
        except Exception as e:
            logger.error("[VaultCompiler] compile_state failed: %s", e)

    def compile_relationship(self, relationship_state) -> None:
        """Write the relationship.md file from a RelationshipState snapshot.

        Phase 2: RelationshipUpdater now holds relationship as runtime state and
        compiles it here instead of writing markdown directly.
        """
        if self._writer is None:
            return
        try:
            self._writer.write_relationship(relationship_state)
            logger.debug("[VaultCompiler] compiled RelationshipState -> relationship.md")
        except Exception as e:
            logger.error("[VaultCompiler] compile_relationship failed: %s", e)

    # ── Phase 3: proposed-layout generators ──

    def compile_graph(self, graph_manager=None) -> dict:
        """Export the knowledge graph to the canonical `graph/` folder.

        Phase 3/4 of the State-First architecture: the graph is exported as
        `graph/entities.md` + `graph/relations.md` (and json). The legacy
        `Entities/` directory has been retired in favor of `graph/`.
        """
        if self._writer is None or not self.vault_root:
            return {"written": 0}
        try:
            result = self._writer.export_graph(self.vault_root / "graph", graph_manager)
            self.logger.maintenance_run("graph export")
            return result
        except Exception as e:
            logger.error("[VaultCompiler] compile_graph failed: %s", e)
            return {"written": 0}

    def compile_index(self) -> None:
        """Generate the vault `index.md` table of contents."""
        if self._writer is None or not self.vault_root:
            return
        try:
            lines = ["# Mai Memory — Index", "",
                     "_Generated by VaultCompiler. Edit runtime state, not this file._", ""]
            for folder in sorted(VAULT_FOLDERS):
                fpath = self.vault_root / folder
                if fpath.is_dir():
                    count = len(list(fpath.glob("*.md")))
                    lines.append(f"- [[{folder}/]] — {count} notes")
            for fname in sorted(VAULT_FILES):
                if (self.vault_root / fname).exists():
                    lines.append(f"- [[{fname}]]")
            (self.vault_root / "index.md").write_text("\n".join(lines), encoding="utf-8")
        except Exception as e:
            logger.error("[VaultCompiler] compile_index failed: %s", e)

    def compile_schema(self) -> None:
        """Generate the vault `schema.md` documenting the canonical layout."""
        if self._writer is None or not self.vault_root:
            return
        try:
            lines = ["# Mai Memory — Vault Schema", "",
                     "_Generated by VaultCompiler from knowledge.vault_schema._", "",
                     "## Folders", ""]
            for folder in sorted(VAULT_FOLDERS):
                meta = VAULT_SCHEMA.get(folder, {})
                lines.append(f"- `{folder}/` — owner: **{meta.get('owner')}**, "
                             f"mode: {meta.get('mode')}")
            lines.append("")
            lines.append("## Files")
            for fname, owner in sorted(VAULT_FILES.items()):
                lines.append(f"- `{fname}` — owner: **{owner}**")
            (self.vault_root / "schema.md").write_text("\n".join(lines), encoding="utf-8")
        except Exception as e:
            logger.error("[VaultCompiler] compile_schema failed: %s", e)

    def stats(self) -> dict:
        base = self._writer.stats() if self._writer else {}
        base["compiler_owned_folders"] = sorted(COMPILER_OWNED_FOLDERS)
        return base
